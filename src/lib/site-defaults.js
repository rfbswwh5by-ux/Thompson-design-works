/**
 * A value saved in the dashboard always wins, even when it was cleared to blank;
 * the built-in default only fills a field that has never been saved.
 */
export function savedText(record, key, fallback = "") {
  const value = record?.[key];
  return typeof value === "string" ? value : fallback;
}

